def collect_tag_descriptions() -> Dict[str, str]:
    tree = parse("auth_server.py")
    tags: Dict[str, str] = {}
    if tree is None:
        return tags
    for node in ast.walk(tree):
        if isinstance(node, ast.Assign) and any(
            isinstance(t, ast.Name) and t.id == "tags_metadata" for t in node.targets
        ) and isinstance(node.value, ast.List):
            for item in node.value.elts:
                if not isinstance(item, ast.Dict):
                    continue
                pairs = {const_str(k): const_str(v) for k, v in zip(item.keys, item.values)}
                if pairs.get("name"):
                    tags[pairs["name"]] = pairs.get("description") or ""
    return tags


def path_literal(node: ast.AST) -> Optional[str]:
    """A route path, including f-strings (rendered with their ``{expr}`` holes)."""
    literal = const_str(node)
    if literal is not None:
        return literal
    if isinstance(node, ast.JoinedStr):
        out = []
        for part in node.values:
            if isinstance(part, ast.Constant):
                out.append(str(part.value))
            elif isinstance(part, ast.FormattedValue):
                out.append("{" + ast.unparse(part.value) + "}")
        return "".join(out)
    return None


def collect_routes(sources: Sequence[str]) -> List[Dict[str, str]]:
    routes: List[Dict[str, str]] = []
    for path in sources:
        tree = parse(path)
        if tree is None:
            continue

        routers: Dict[str, Dict[str, Any]] = {}
        for node in ast.walk(tree):
            if isinstance(node, ast.Assign) and isinstance(node.value, ast.Call) \
                    and dotted(node.value.func).endswith("APIRouter"):
                prefix, tags = "", []
                for kw in node.value.keywords:
                    if kw.arg == "prefix":
                        prefix = const_str(kw.value) or ""
                    elif kw.arg == "tags" and isinstance(kw.value, ast.List):
                        tags = [const_str(e) for e in kw.value.elts if const_str(e)]
                for target in node.targets:
                    if isinstance(target, ast.Name):
                        routers[target.id] = {"prefix": prefix, "tags": tags}

        for node in ast.walk(tree):
            if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                continue
            for dec in node.decorator_list:
                if not (isinstance(dec, ast.Call) and isinstance(dec.func, ast.Attribute)):
                    continue
                method = dec.func.attr
                if method not in HTTP_METHODS or not dec.args:
                    continue
                route_path = path_literal(dec.args[0])
                if route_path is None:
                    continue
                owner = dotted(dec.func.value)
                router = routers.get(owner, {"prefix": "", "tags": []})
                tags = list(router["tags"])
                methods = [method.upper()]
                for kw in dec.keywords:
                    if kw.arg == "tags" and isinstance(kw.value, ast.List):
                        tags = [const_str(e) for e in kw.value.elts if const_str(e)] or tags
                    elif kw.arg == "methods" and isinstance(kw.value, ast.List):
                        methods = [const_str(e) for e in kw.value.elts if const_str(e)]
                if method == "websocket":
                    methods = ["WS"]
                elif method == "api_route" and methods == ["API_ROUTE"]:
                    methods = ["ANY"]
                routes.append({
                    "method": ", ".join(methods),
                    "path": router["prefix"] + route_path,
                    "tag": tags[0] if tags else "Untagged",
                    "summary": first_line(ast.get_docstring(node)),
                    "source": f"{path} · {node.name}",
                })
    return routes


# Which process serves a route, decided by the file that declares it. Order matters:
# first match wins, and the last entry is the catch-all.
SERVERS = (
    ("Agent server: ADK runtime", "Internal, port 8001. Reached through the auth "
     "server's proxy, not exposed directly.", ("adk_main.py",)),
    ("Agent server: LangGraph runtime", "Used instead of the ADK runtime when "
     "`AGENT_FRAMEWORK=langgraph`; emulates the same HTTP/SSE contract.",
     ("langgraph_main.py", "shared/utils/langgraph/**")),
    ("Standalone server", "The single-agent binary built by "
     "`build_standalone_agent.py`.", ("standalone_server.py",)),
    ("Auth server and dashboard", "Port 8000. Everything a browser or an external "
     "client talks to.", ("**",)),
)


def server_for(source_file: str) -> str:
    for name, _, patterns in SERVERS:
        if any(glob_to_regex(p).match(source_file) for p in patterns):
            return name
    return SERVERS[-1][0]


def render_api(sources: Sequence[str]) -> str:
    routes = collect_routes(sources)
    descriptions = collect_tag_descriptions()
    grouped: Dict[str, Dict[str, List[Dict[str, str]]]] = {}
    for route in routes:
        server = server_for(route["source"].split(" · ")[0])
        grouped.setdefault(server, {}).setdefault(route["tag"], []).append(route)

    undocumented = sum(1 for r in routes if not r["summary"])
    body = [
        f"Every HTTP route declared in the code: **{len(routes)}** routes. "
        f"{undocumented} have no docstring and so no summary here.",
        "",
        "This page lists what exists and where it is implemented. For request and "
        "response schemas, and to try a call, use the live Swagger UI under "
        "**Documentation → API** in the dashboard.",
        "",
        "Requests to `/dashboard/api/*` require an admin, apart from the short allowlist "
        "in `server/dashboard_authz.py`.",
    ]
    # Catch-all (the public surface) first, then the internal servers.
    for name, blurb, _ in (SERVERS[-1],) + SERVERS[:-1]:
        tags = grouped.get(name)
        if not tags:
            continue
        count = sum(len(v) for v in tags.values())
        body += ["", f"## {name}", "", f"{blurb} {count} routes."]
        for tag in sorted(tags, key=lambda t: (t == "Untagged", t)):
            body += ["", f"### {'Other' if tag == 'Untagged' else tag}", ""]
            if descriptions.get(tag):
                body += [descriptions[tag].rstrip(".") + ".", ""]
            rows = [
                [code(r["method"]), code(r["path"]), cell(r["summary"]), cell(r["source"])]
                for r in sorted(tags[tag], key=lambda r: (r["path"], r["method"]))
            ]
            body.append(table(["Method", "Path", "Summary", "Implemented in"], rows))
    return page(
        "HTTP API reference",
        "Every HTTP route, grouped by server and area, with a summary and where it lives.",
        20, "\n".join(body),
    )


