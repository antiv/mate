MODELS = "shared/utils/models.py"
MIGRATION_FILE = re.compile(r"^V(\d+)__(.+)\.sql$")


def column_comment(lines: Sequence[str], node: ast.Assign) -> str:
    """The comment explaining a column: trailing on its line, else the block above it."""
    for lineno in range(node.lineno, (node.end_lineno or node.lineno) + 1):
        _, sep, trailing = lines[lineno - 1].partition("  # ")
        if sep:
            return trailing.strip()
    block: List[str] = []
    lineno = node.lineno - 2
    while lineno >= 0 and lines[lineno].strip().startswith("#"):
        block.insert(0, lines[lineno].strip().lstrip("#").strip())
        lineno -= 1
    return " ".join(block)


def migration_versions() -> Dict[int, Dict[str, str]]:
    """{version: {dialect: name}} for every migration file in the dialect folders."""
    versions: Dict[int, Dict[str, str]] = {}
    for dialect in SQL_DIALECTS:
        folder = ROOT / "shared" / "sql" / "migrations" / dialect
        if not folder.is_dir():
            continue
        for entry in folder.iterdir():
            match = MIGRATION_FILE.match(entry.name)
            if match:
                versions.setdefault(int(match.group(1)), {})[dialect] = match.group(2)
    return versions


def migration_gaps() -> List[str]:
    """Each migration version missing from a dialect, e.g. ``V036 has no mysql file``.

    An installation on that database type would silently never get the change.
    """
    return [
        f"V{version:03d} has no {dialect} file"
        for version, present in sorted(migration_versions().items())
        for dialect in SQL_DIALECTS if dialect not in present
    ]


def render_database() -> str:
    tree = parse(MODELS)
    lines = (ROOT / MODELS).read_text(encoding="utf-8").splitlines() if tree else []
    body: List[str] = []
    tables: List[Tuple[str, str]] = []

    for node in tree.body if tree else []:
        if not isinstance(node, ast.ClassDef):
            continue
        table_name = None
        columns: List[List[str]] = []
        for item in node.body:
            if not isinstance(item, ast.Assign) or len(item.targets) != 1:
                continue
            target = item.targets[0]
            if not isinstance(target, ast.Name):
                continue
            if target.id == "__tablename__":
                table_name = const_str(item.value)
                continue
            call = item.value
            if not (isinstance(call, ast.Call) and dotted(call.func) == "Column"):
                continue
            col_type, flags = "", []
            for arg in call.args:
                if isinstance(arg, ast.Call) and dotted(arg.func) == "ForeignKey":
                    flags.append(f"FK → `{const_str(arg.args[0]) if arg.args else '?'}`")
                elif not col_type:
                    col_type = ast.unparse(arg)
            default = ""
            for kw in call.keywords:
                if kw.arg == "primary_key" and getattr(kw.value, "value", False) is True:
                    flags.insert(0, "PK")
                elif kw.arg == "unique" and getattr(kw.value, "value", False) is True:
                    flags.append("unique")
                elif kw.arg == "nullable" and getattr(kw.value, "value", True) is False:
                    flags.append("not null")
                elif kw.arg == "default":
                    default = "(computed)" if isinstance(kw.value, ast.Lambda) \
                        else ast.unparse(kw.value)
            columns.append([
                code(target.id), code(col_type), cell(", ".join(flags)),
                code(default), cell(column_comment(lines, item)),
            ])
        if not table_name:
            continue
        tables.append((table_name, node.name))
        section = [f"## `{table_name}`", "", f"Model `{node.name}`."]
        doc = first_line(ast.get_docstring(node))
        if doc:
            section[-1] += f" {doc}."
        section += ["", table(["Column", "Type", "Constraints", "Default", "Notes"], columns)]
        body.append("\n".join(section))

    # Migrations, and whether every dialect has every version.
    versions = migration_versions()
    migration_rows = []
    gaps = 0
    for version in sorted(versions):
        present = versions[version]
        name = next(iter(present[d] for d in SQL_DIALECTS if d in present))
        marks = ["✓" if d in present else "✗" for d in SQL_DIALECTS]
        gaps += marks.count("✗")
        migration_rows.append([f"V{version:03d}", cell(name.replace("_", " "))] + marks)

    latest = f"V{max(versions):03d}" if versions else "none"
    intro = [
        f"**{len(tables)}** tables defined in `{MODELS}`; migrations are at **{latest}**. "
        "Migrations apply automatically on startup and are the source of truth for the "
        "schema: the models describe it, the migrations create it.",
        "",
        "## Migrations",
        "",
        "A ✗ means that dialect has no file for that version."
        + (f" **{gaps} gap(s) found.**" if gaps else " All dialects are in step."),
        "",
        table(["Version", "Name"] + list(SQL_DIALECTS), migration_rows),
        "",
    ]
    return page(
        "Database reference",
        "Every table and column from the ORM models, plus the migration history per dialect.",
        40, "\n".join(intro) + "\n" + "\n\n".join(body),
    )


