def rel(path: Path) -> str:
    """Repo-relative path with forward slashes."""
    return path.relative_to(ROOT).as_posix()


def tracked_files() -> List[str]:
    """Every file in the repo, preferring git's view and falling back to a walk.

    Untracked files that are not ignored are included, so a new module shows up
    before it is staged. Keep scratch scripts ignored or outside the repo, or
    they will appear in the reference locally and not in CI.
    """
    try:
        out = subprocess.run(
            ["git", "ls-files", "--cached", "--others", "--exclude-standard"],
            cwd=ROOT, capture_output=True, text=True, check=True,
        ).stdout
        files = [line for line in out.splitlines() if line and (ROOT / line).is_file()]
        if files:
            return sorted(files)
    except (OSError, subprocess.CalledProcessError):
        pass
    found: List[str] = []
    for dirpath, dirnames, filenames in os.walk(ROOT):
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
        for name in filenames:
            found.append(rel(Path(dirpath) / name))
    return sorted(found)


def python_sources(files: Sequence[str]) -> List[str]:
    return [
        f for f in files
        if f.endswith(".py")
        and not f.startswith(SKIP_PREFIXES)
        and not (set(f.split("/")) & SKIP_DIRS)
    ]


def parse(path: str) -> Optional[ast.Module]:
    try:
        return ast.parse((ROOT / path).read_text(encoding="utf-8"), filename=path)
    except (SyntaxError, UnicodeDecodeError, OSError):
        return None


def glob_to_regex(pattern: str) -> "re.Pattern[str]":
    """Translate a path glob to a regex. ``**`` spans directories, ``*`` does not."""
    out = []
    i = 0
    while i < len(pattern):
        if pattern.startswith("**/", i):
            out.append("(?:.*/)?")
            i += 3
        elif pattern.startswith("**", i):
            out.append(".*")
            i += 2
        elif pattern[i] == "*":
            out.append("[^/]*")
            i += 1
        elif pattern[i] == "?":
            out.append("[^/]")
            i += 1
        else:
            out.append(re.escape(pattern[i]))
            i += 1
    return re.compile("^" + "".join(out) + "$")


# --------------------------------------------------------------------------- #
# Markdown helpers                                                             #
# --------------------------------------------------------------------------- #

def cell(text: Any) -> str:
    """Make a value safe for a Markdown table cell."""
    s = "" if text is None else str(text)
    s = re.sub(r"\s+", " ", s).strip()
    return s.replace("|", "\\|") or "—"


def code(text: Any) -> str:
    s = "" if text is None else str(text)
    return f"`{s}`" if s else "—"


def table(headers: Sequence[str], rows: Iterable[Sequence[str]]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    lines.extend("| " + " | ".join(row) + " |" for row in rows)
    return "\n".join(lines)


def page(title: str, summary: str, order: int, body: str) -> str:
    front = "\n".join([
        "---",
        f"title: {title}",
        f"summary: {summary}",
        "audience: dev",
        f"order: {order}",
        "generated: true",
        "---",
    ])
    return f"{front}\n\n{GENERATED_BANNER}\n\n# {title}\n\n{body.rstrip()}\n"


def first_line(doc: Optional[str]) -> str:
    """The first sentence of a docstring's first paragraph, without the full stop."""
    if not doc:
        return ""
    paragraph = " ".join(doc.strip().split("\n\n", 1)[0].split())
    sentence = re.split(r"(?<=[.!?])\s", paragraph, maxsplit=1)[0]
    if len(sentence) > 180:
        sentence = sentence[:177].rstrip() + "..."
    return sentence.rstrip(".")


def dotted(node: ast.AST) -> str:
    """``a.b.c`` for a Name/Attribute chain, else an empty string."""
    parts: List[str] = []
    while isinstance(node, ast.Attribute):
        parts.append(node.attr)
        node = node.value
    if isinstance(node, ast.Name):
        parts.append(node.id)
        return ".".join(reversed(parts))
    return ""


def const_str(node: Optional[ast.AST]) -> Optional[str]:
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    return None


# --------------------------------------------------------------------------- #
# Reference: configuration (environment variables)                             #
# --------------------------------------------------------------------------- #

ENV_NAME = re.compile(r"^[A-Z][A-Z0-9_]*$")
ENV_EXAMPLE_VAR = re.compile(r"^\s*#?\s*([A-Z][A-Z0-9_]*)=(.*)$")
ENV_EXAMPLE_CONTINUATION = re.compile(r"^#\s+#\s?(.*)$")


ENV_READERS = ("os.getenv", "os.environ.get", "environ.get", "getenv")
# Read by the code, but the operating system's business rather than MATE's.
ENV_IGNORED = {"PATH"}


def env_wrappers(tree: ast.Module) -> Dict[str, Optional[str]]:
    """Module-local helpers that forward their first argument to ``os.getenv``.

    ``def _cfg(key, default=""): return os.getenv(key, default)`` makes every
    ``_cfg("NAME")`` an env read. Maps the helper's name to its own default.
    """
    wrappers: Dict[str, Optional[str]] = {}
    for node in ast.walk(tree):
        if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) or not node.args.args:
            continue
        first = node.args.args[0].arg
        forwards = any(
            isinstance(call, ast.Call) and dotted(call.func) in ENV_READERS and call.args
            and isinstance(call.args[0], ast.Name) and call.args[0].id == first
            for call in ast.walk(node)
        )
        if not forwards:
            continue
        default: Optional[str] = None
        if len(node.args.args) > 1 and node.args.defaults:
            last = node.args.defaults[-1]
            if isinstance(last, ast.Constant) and last.value is not None:
                default = str(last.value)
        wrappers[node.name] = default
    return wrappers


def collect_env_reads(sources: Sequence[str]) -> Dict[str, Dict[str, Set[str]]]:
    """Map each env var read in code to the files reading it and the defaults used."""
    found: Dict[str, Dict[str, Set[str]]] = {}

    def record(name: str, path: str, default: Optional[str]) -> None:
        if not ENV_NAME.match(name) or name in ENV_IGNORED:
            return
        entry = found.setdefault(name, {"files": set(), "defaults": set()})
        entry["files"].add(path)
        if default is not None:
            entry["defaults"].add(default)

    for path in sources:
        tree = parse(path)
        if tree is None:
            continue
        wrappers = env_wrappers(tree)
        for node in ast.walk(tree):
            if isinstance(node, ast.Call):
                target = dotted(node.func)
                if (target in ENV_READERS or target in wrappers) and node.args:
                    name = const_str(node.args[0])
                    if name is None:
                        continue
                    default_node = node.args[1] if len(node.args) > 1 else None
                    for kw in node.keywords:
                        if kw.arg == "default":
                            default_node = kw.value
                    if default_node is None:
                        default = wrappers.get(target)
                    elif isinstance(default_node, ast.Constant):
                        default = None if default_node.value is None else str(default_node.value)
                    else:
                        default = "(computed)"
                    record(name, path, default)
            elif isinstance(node, ast.Subscript) and isinstance(node.ctx, ast.Load):
                if dotted(node.value) in ("os.environ", "environ"):
                    name = const_str(node.slice)
                    if name is not None:
                        record(name, path, None)
    return found


def parse_env_example() -> Dict[str, Dict[str, str]]:
    """Read ``.env.example``: the example value and the comment explaining each variable."""
    path = ROOT / ".env.example"
    if not path.is_file():
        return {}
    lines = path.read_text(encoding="utf-8").splitlines()
    result: Dict[str, Dict[str, str]] = {}
    pending_comment: List[str] = []
    pending_start = -1
    i = 0
    while i < len(lines):
        line = lines[i]
        match = ENV_EXAMPLE_VAR.match(line)
        if match:
            name, rest = match.group(1), match.group(2)
            value, _, inline = rest.partition(" #")
            description = [inline.strip()] if inline.strip() else []
            while i + 1 < len(lines):
                cont = ENV_EXAMPLE_CONTINUATION.match(lines[i + 1])
                if not cont:
                    break
                description.append(cont.group(1).strip())
                i += 1
            # A comment block directly above a variable describes it, unless it is
            # the banner at the top of the file.
            if not description and pending_comment and pending_start > 0:
                description = pending_comment
            result.setdefault(name, {
                "example": value.strip(),
                "description": " ".join(d for d in description if d),
            })
            pending_comment = []
        elif line.strip().startswith("#"):
            text = line.strip().lstrip("#").strip()
            if text:
                if not pending_comment:
                    pending_start = i
                pending_comment.append(text)
        else:
            pending_comment = []
        i += 1
    return result


def configuration_gaps(
    reads: Dict[str, Dict[str, Set[str]]], example: Dict[str, Dict[str, str]],
) -> Tuple[List[str], List[str]]:
    """Conflicting defaults and reads without an entry in the env template."""
    conflicts = sorted(name for name, entry in reads.items() if len(entry["defaults"]) > 1)
    undocumented = sorted(name for name in reads if name not in example)
    return conflicts, undocumented


def render_configuration(sources: Sequence[str]) -> str:
    reads = collect_env_reads(sources)
    example = parse_env_example()
    conflicts, undocumented = configuration_gaps(reads, example)
    unread = sorted(n for n in example if n not in reads)

    rows = []
    for name in sorted(reads):
        entry = reads[name]
        defaults = sorted(entry["defaults"])
        default_text = " / ".join(code(d) for d in defaults) if defaults else "—"
        if name in conflicts:
            default_text += " ⚠"
        files = sorted(entry["files"])
        shown = ", ".join(code(f) for f in files[:3])
        if len(files) > 3:
            shown += f" +{len(files) - 3} more"
        rows.append([
            code(name), default_text,
            cell(example.get(name, {}).get("description", "")), shown,
        ])

    body = [
        f"Every environment variable the code reads: **{len(reads)}** in total. "
        "Descriptions come from the comments in `.env.example`; defaults come from the "
        "code. A ⚠ marks a variable read with different defaults in different places.",
        "",
        table(["Variable", "Default", "Description", "Read in"], rows),
    ]
    if undocumented:
        body += [
            "", "## Read by the code but missing from `.env.example`", "",
            f"{len(undocumented)} variables have no entry (and so no description) in "
            "`.env.example`:", "",
            ", ".join(code(n) for n in undocumented),
        ]
    if unread:
        body += [
            "", "## In `.env.example` but not read by MATE's own code", "",
            "Usually consumed by a library (LiteLLM provider keys, OpenTelemetry, "
            "LangSmith) rather than by MATE directly; otherwise a leftover:", "",
            ", ".join(code(n) for n in unread),
        ]
    return page(
        "Configuration reference",
        "Every environment variable MATE reads, with defaults and where it is used.",
        10, "\n".join(body),
    )


