TOOL_FACTORY = "shared/utils/tools/tool_factory.py"


def render_tools() -> str:
    tree = parse(TOOL_FACTORY)
    creators: Dict[str, str] = {}
    methods: Dict[str, ast.FunctionDef] = {}
    special: Set[str] = set()
    if tree is not None:
        for node in ast.walk(tree):
            if isinstance(node, ast.ClassDef) and node.name == "ToolFactory":
                for item in node.body:
                    if isinstance(item, ast.FunctionDef):
                        methods[item.name] = item
            if isinstance(node, ast.Assign) and isinstance(node.value, ast.Dict) and any(
                dotted(t) == "self._tool_creators" for t in node.targets
            ):
                for key, value in zip(node.value.keys, node.value.values):
                    name = const_str(key)
                    if name and isinstance(value, ast.Attribute):
                        creators[name] = value.attr
            # tool_config keys handled inline rather than through the registry
            if isinstance(node, ast.Compare) and dotted(node.left) == "tool_type" \
                    and len(node.ops) == 1 and isinstance(node.ops[0], ast.Eq):
                literal = const_str(node.comparators[0])
                if literal:
                    special.add(literal)

    rows = []
    for key in sorted(creators):
        method = methods.get(creators[key])
        description, module = "", ""
        if method is not None:
            description = first_line(ast.get_docstring(method))
            for sub in ast.walk(method):
                if isinstance(sub, ast.ImportFrom) and sub.module:
                    base = "shared/utils/tools/" if sub.level == 1 else ""
                    module = base + sub.module.replace(".", "/") + ".py"
                    break
        rows.append([code(key), cell(description), code(module)])

    inline_only = sorted(special - set(creators))
    body = [
        f"The tool types an agent can enable through its `tool_config` JSON: "
        f"**{len(creators)}** registered in `ToolFactory._tool_creators`.",
        "",
        "A key enables its tools when present with a non-null value, for example "
        '`{"memory_blocks": true, "file_search": true}`.',
        "",
        table(["`tool_config` key", "What it adds", "Implemented in"], rows),
    ]
    if inline_only:
        body += [
            "", "## Keys handled outside the registry", "",
            "Handled by a dedicated branch in `ToolFactory.create_tools` rather than a "
            "registered creator:", "",
            ", ".join(code(k) for k in inline_only),
        ]
    return page(
        "Tool reference",
        "Every tool type an agent can enable through tool_config, and where it is implemented.",
        30, "\n".join(body),
    )


