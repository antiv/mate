#!/usr/bin/env python3
"""Generate and check MATE's documentation.

The docs tree has two kinds of pages:

* ``docs/reference/*.md`` is generated from the code by this script and is
  never edited by hand. It cannot drift: CI regenerates it and fails when the
  committed copy differs.
* ``docs/user/*.md`` and ``docs/dev/*.md`` are guides written by people (or by
  an agent and reviewed by people). Each one declares, in its frontmatter, the
  code it describes (``covers:``). When that code changes and the guide does
  not, the guide is reported as possibly stale.

Usage::

    python scripts/gen_docs.py                 # regenerate docs/reference/
    python scripts/gen_docs.py --check         # CI: reference up to date + guides well-formed
    python scripts/gen_docs.py drift --base origin/main [--strict]
    python scripts/gen_docs.py coverage        # which source files no guide covers

Everything here is static analysis (``ast``) over the working tree. Nothing is
imported from the application, so the script needs no dependencies, no database
and no running server, and its output is deterministic: no timestamps and no
line numbers, both of which would make the reference "change" on every commit.
"""

from __future__ import annotations

import argparse
import ast
import fnmatch
import os
import re
import subprocess
import sys
from pathlib import Path
from typing import Any, Dict, Iterable, List, Optional, Sequence, Set, Tuple

ROOT = Path(__file__).resolve().parent.parent
DOCS_DIR = ROOT / "docs"
REFERENCE_DIR = DOCS_DIR / "reference"
GUIDE_DIRS = {"user": DOCS_DIR / "user", "dev": DOCS_DIR / "dev"}

GENERATED_BANNER = (
    "<!-- AUTO-GENERATED by scripts/gen_docs.py. Do not edit: "
    "change the code, then run `python scripts/gen_docs.py`. -->"
)

# Directories that never hold application code worth documenting.
SKIP_DIRS = {
    ".git", ".venv", "venv", "node_modules", "__pycache__", "build", "dist",
    ".codegraph", ".claude",
}
# Tests read env vars and declare routes of their own; they are not the product.
SKIP_PREFIXES = ("shared/test/", "scripts/gen_docs.py")

# These are managed by the application, rather than configured by operators.
ENV_EXAMPLE_ALLOWLIST = {
    "TIKTOKEN_CACHE_DIR": "build_standalone_agent.py sets the tokenizer cache directory",
}

# Source areas a guide is expected to cover, for the coverage report.
COVERAGE_GLOBS = (
    "auth_server.py", "adk_main.py", "langgraph_main.py", "standalone_server.py",
    "server/**", "shared/callbacks/**", "shared/utils/**",
    "templates/dashboard/**", "static/js/**",
)

HTTP_METHODS = {"get", "post", "put", "delete", "patch", "websocket", "api_route"}
SQL_DIALECTS = ("sqlite", "postgresql", "mysql")


