def cmd_generate(check: bool) -> int:
    reference = build_reference()
    stale: List[str] = []
    for name, content in reference.items():
        target = REFERENCE_DIR / name
        current = target.read_text(encoding="utf-8") if target.is_file() else None
        if current == content:
            continue
        stale.append(rel(target) if target.exists() else f"docs/reference/{name}")
        if not check:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8")

    if not check:
        print(f"docs/reference: {len(reference)} pages, {len(stale)} updated")
        return 0

    failed = False
    reads = collect_env_reads(python_sources(tracked_files()))
    conflicts, undocumented = configuration_gaps(reads, parse_env_example())
    if conflicts:
        failed = True
        print("Conflicting environment variable defaults (define the default once in shared/utils/settings.py):")
        for name in conflicts:
            defaults = ", ".join(sorted(reads[name]["defaults"]))
            files = ", ".join(sorted(reads[name]["files"]))
            print(f"  - {name}: defaults {defaults}; read in {files}")
    missing = [name for name in undocumented if name not in ENV_EXAMPLE_ALLOWLIST]
    if missing:
        failed = True
        print("Environment variables missing from .env.example (add a commented line with a description):")
        for name in missing:
            print(f"  - {name}")
    if stale:
        failed = True
        print("Generated reference is out of date. Run `python scripts/gen_docs.py` and commit:")
        for name in stale:
            print(f"  - {name}")
    problems = lint_guides(tracked_files())
    if problems:
        failed = True
        print("Guide problems:")
        for problem in problems:
            print(f"  - {problem}")
    gaps = migration_gaps()
    if gaps:
        failed = True
        print("Migrations missing from a dialect (add the file to shared/sql/migrations/<dialect>/):")
        for gap in gaps:
            print(f"  - {gap}")
    if not failed:
        print(f"docs OK: {len(reference)} reference pages current, {len(guides())} guides well-formed")
        unverified = [rel(g) for g in guides() if read_frontmatter(g)[0].get("status") == "migrated"]
        if unverified:
            print(f"{len(unverified)} guide(s) still marked `status: migrated` (not re-checked against the code)")
    return 1 if failed else 0


def cmd_drift(base: str, strict: bool) -> int:
    stale, error = find_drift(base)
    if error:
        print(f"drift check skipped: {error}")
        return 1 if strict else 0
    if not stale:
        print(f"No guide drift against {base}.")
        return 0
    in_actions = os.getenv("GITHUB_ACTIONS") == "true"
    print(f"{len(stale)} guide(s) describe code that changed but were not updated:")
    for name, reasons in stale:
        print(f"  - {name}")
        for reason in reasons:
            print(f"      {reason}")
        if in_actions:
            level = "error" if strict else "warning"
            print(f"::{level} file={name}::Covered code changed without this guide: "
                  f"{', '.join(reasons)}")
    print("Update the guide, or confirm it is still accurate and say so in the PR.")
    return 1 if strict else 0


def cmd_coverage() -> int:
    covered, uncovered = coverage_report(tracked_files())
    total = len(covered) + len(uncovered)
    percent = (100 * len(covered) // total) if total else 0
    print(f"Guide coverage: {len(covered)}/{total} source files ({percent}%)")
    by_dir: Dict[str, List[str]] = {}
    for path in uncovered:
        by_dir.setdefault(os.path.dirname(path) or ".", []).append(os.path.basename(path))
    for folder in sorted(by_dir):
        print(f"\n{folder}/ ({len(by_dir[folder])} uncovered)")
        for name in sorted(by_dir[folder]):
            print(f"  {name}")
    return 0


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="fail if docs/reference is stale or a guide is malformed")
    sub = parser.add_subparsers(dest="command")
    drift = sub.add_parser("drift", help="report guides whose covered code changed")
    drift.add_argument("--base", default="origin/main", help="git ref to compare against")
    drift.add_argument("--strict", action="store_true", help="exit 1 when a guide is stale")
    sub.add_parser("coverage", help="list source files no guide covers")
    args = parser.parse_args(argv)

    if args.command == "drift":
        return cmd_drift(args.base, args.strict)
    if args.command == "coverage":
        return cmd_coverage()
    return cmd_generate(args.check)


if __name__ == "__main__":
    sys.exit(main())
