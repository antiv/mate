def read_frontmatter(path: Path) -> Tuple[Dict[str, Any], str]:
    """Parse the small YAML subset guides use: scalars, ``[a, b]`` and ``- item`` lists."""
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        return {}, text
    end = text.find("\n---", 4)
    if end == -1:
        return {}, text
    meta: Dict[str, Any] = {}
    current: Optional[str] = None
    for raw in text[4:end].splitlines():
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        item = re.match(r"^\s+-\s+(.*)$", raw)
        if item and current:
            meta.setdefault(current, [])
            if isinstance(meta[current], list):
                meta[current].append(item.group(1).strip().strip("\"'"))
            continue
        pair = re.match(r"^([A-Za-z_][\w-]*):\s*(.*)$", raw)
        if not pair:
            continue
        current, value = pair.group(1), pair.group(2).strip()
        if value == "":
            meta[current] = []
        elif value.startswith("[") and value.endswith("]"):
            meta[current] = [v.strip().strip("\"'") for v in value[1:-1].split(",") if v.strip()]
        else:
            meta[current] = value.strip("\"'")
    return meta, text[end + 4:]


def guides() -> List[Path]:
    found: List[Path] = []
    for folder in GUIDE_DIRS.values():
        if folder.is_dir():
            found.extend(sorted(folder.rglob("*.md")))
    return found


def symbols(source: str, pattern: str) -> Dict[str, str]:
    """Functions and classes whose name matches ``pattern``, keyed to a body fingerprint.

    The fingerprint is ``ast.dump``: it ignores comments and formatting, so only a
    change in behaviour counts as a change.
    """
    try:
        tree = ast.parse(source)
    except SyntaxError:
        return {}
    out: Dict[str, str] = {}
    for node in ast.walk(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)) \
                and fnmatch.fnmatchcase(node.name, pattern):
            out[node.name] = out.get(node.name, "") + ast.dump(node)
    return out


def split_cover(entry: str) -> Tuple[str, Optional[str]]:
    path, sep, symbol = entry.partition("::")
    return path, (symbol if sep else None)


def lint_guides(files: Sequence[str]) -> List[str]:
    problems: List[str] = []
    file_set = set(files)
    for guide in guides():
        name = rel(guide)
        meta, body = read_frontmatter(guide)
        if not meta:
            problems.append(f"{name}: missing frontmatter")
            continue
        for key in ("title", "summary", "audience", "covers"):
            if key not in meta:
                problems.append(f"{name}: frontmatter is missing `{key}`")
        expected = guide.relative_to(DOCS_DIR).parts[0]
        if meta.get("audience") not in (None, expected):
            problems.append(
                f"{name}: audience is `{meta.get('audience')}` but the file is under docs/{expected}/"
            )
        covers = meta.get("covers") or []
        if not isinstance(covers, list):
            problems.append(f"{name}: `covers` must be a list")
            covers = []
        for entry in covers:
            path, symbol = split_cover(entry)
            regex = glob_to_regex(path)
            matched = [f for f in files if regex.match(f)]
            if not matched:
                problems.append(f"{name}: `covers` entry `{entry}` matches no file (renamed or removed?)")
            elif symbol and not any(
                symbols((ROOT / f).read_text(encoding="utf-8"), symbol) for f in matched
            ):
                problems.append(f"{name}: `covers` entry `{entry}` matches no function or class")
        for link in re.findall(r"\]\(([^)\s]+)\)", body):
            if re.match(r"^(https?:|mailto:|#|/)", link):
                continue
            target = (guide.parent / link.split("#", 1)[0]).resolve()
            try:
                target_rel = target.relative_to(ROOT).as_posix()
            except ValueError:
                target_rel = ""
            if target_rel not in file_set and not target.exists():
                problems.append(f"{name}: broken link `{link}`")
    return problems


def git(*args: str) -> Optional[str]:
    try:
        return subprocess.run(
            ["git", *args], cwd=ROOT, capture_output=True, text=True, check=True,
        ).stdout
    except (OSError, subprocess.CalledProcessError):
        return None


def find_drift(base: str) -> Tuple[List[Tuple[str, List[str]]], Optional[str]]:
    """Guides whose covered code changed since ``base`` while the guide did not."""
    merge_base = (git("merge-base", base, "HEAD") or "").strip()
    if not merge_base:
        return [], f"cannot resolve base `{base}` (shallow clone? fetch it first)"
    diff = git("diff", "--name-only", merge_base)
    if diff is None:
        return [], "git diff failed"
    changed = {line for line in diff.splitlines() if line}
    untracked = git("ls-files", "--others", "--exclude-standard") or ""
    changed |= {line for line in untracked.splitlines() if line}

    stale: List[Tuple[str, List[str]]] = []
    for guide in guides():
        name = rel(guide)
        if name in changed:
            continue
        meta, _ = read_frontmatter(guide)
        reasons: List[str] = []
        for entry in meta.get("covers") or []:
            path, symbol = split_cover(entry)
            regex = glob_to_regex(path)
            for changed_file in sorted(f for f in changed if regex.match(f)):
                if symbol is None:
                    reasons.append(changed_file)
                    continue
                before = git("show", f"{merge_base}:{changed_file}") or ""
                current = ROOT / changed_file
                after = current.read_text(encoding="utf-8") if current.is_file() else ""
                if symbols(before, symbol) != symbols(after, symbol):
                    reasons.append(f"{changed_file}::{symbol}")
        if reasons:
            stale.append((name, sorted(set(reasons))))
    return stale, None


def coverage_report(files: Sequence[str]) -> Tuple[List[str], List[str]]:
    scope = [
        f for f in files
        if any(glob_to_regex(g).match(f) for g in COVERAGE_GLOBS)
        and f.endswith((".py", ".html", ".js"))
        and not f.endswith("__init__.py")
        and not f.startswith(SKIP_PREFIXES)
    ]
    patterns = []
    for guide in guides():
        meta, _ = read_frontmatter(guide)
        for entry in meta.get("covers") or []:
            patterns.append(glob_to_regex(split_cover(entry)[0]))
    covered = [f for f in scope if any(p.match(f) for p in patterns)]
    uncovered = [f for f in scope if f not in set(covered)]
    return covered, uncovered


